-- CloudNest initial schema. MySQL 8.4, UTC connections, application-owned lifecycle.
CREATE TABLE users (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '用户ID',
 username VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '小写登录名',
 display_name VARCHAR(64) NOT NULL COMMENT '展示名称',
 password_hash VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'bcrypt密码摘要',
 status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'ACTIVE' COMMENT '账号状态',
 storage_quota BIGINT UNSIGNED NOT NULL DEFAULT 107374182400 COMMENT '逻辑配额字节',
 used_storage BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '已发布及回收站用量字节',
 reserved_storage BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '上传预占字节',
 change_seq BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '用户同步序列',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间UTC',
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '更新时间UTC',
 PRIMARY KEY (id),
 UNIQUE KEY uk_users_username (username),
 CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE','DISABLED')),
 CONSTRAINT ck_users_username CHECK (REGEXP_LIKE(username, '^[a-z0-9_]+$', 'c')),
 CONSTRAINT ck_users_quota CHECK (CAST(used_storage AS DECIMAL(20,0)) + CAST(reserved_storage AS DECIMAL(20,0)) <= storage_quota)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='用户及逻辑配额';

CREATE TABLE user_devices (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '设备ID',
 user_id BIGINT UNSIGNED NOT NULL COMMENT '所属用户',
 installation_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '安装UUID',
 name VARCHAR(100) NOT NULL COMMENT '设备名称',
 platform VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '客户端平台',
 os_version VARCHAR(64) NULL COMMENT '系统版本',
 app_version VARCHAR(64) NULL COMMENT '应用版本',
 last_seen_at DATETIME(6) NULL COMMENT '最近认证活动UTC',
 revoked_at DATETIME(6) NULL COMMENT '设备撤销时间UTC',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间UTC',
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '更新时间UTC',
 PRIMARY KEY (id),
 UNIQUE KEY uk_devices_installation (user_id,installation_id),
 UNIQUE KEY uk_devices_owner_id (user_id,id),
 KEY idx_devices_seen (user_id,last_seen_at,id),
 CONSTRAINT fk_devices_user FOREIGN KEY (user_id) REFERENCES users(id),
 CONSTRAINT ck_devices_platform CHECK (platform IN ('WEB','WINDOWS','ANDROID'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='用户设备';

CREATE TABLE auth_sessions (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '认证会话ID',
 user_id BIGINT UNSIGNED NOT NULL COMMENT '所属用户',
 device_id BIGINT UNSIGNED NOT NULL COMMENT '所属设备',
 refresh_token_hash BINARY(32) NOT NULL COMMENT '刷新令牌SHA256摘要',
 token_generation BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '刷新轮换代次',
 expires_at DATETIME(6) NOT NULL COMMENT '会话到期UTC',
 last_seen_at DATETIME(6) NULL COMMENT '最近使用UTC',
 revoked_at DATETIME(6) NULL COMMENT '撤销时间UTC',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间UTC',
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '更新时间UTC',
 PRIMARY KEY (id),
 UNIQUE KEY uk_sessions_refresh (refresh_token_hash),
 KEY idx_sessions_device (user_id,device_id,revoked_at),
 KEY idx_sessions_expiry (expires_at),
 CONSTRAINT fk_sessions_device FOREIGN KEY (user_id,device_id) REFERENCES user_devices(user_id,id),
 CONSTRAINT ck_sessions_generation CHECK (token_generation > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='认证与刷新会话';

CREATE TABLE stored_objects (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '物理对象ID',
 owner_user_id BIGINT UNSIGNED NOT NULL COMMENT '内容所属用户',
 provider VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '存储配置标识',
 bucket VARCHAR(63) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '存储桶',
 object_key VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '不可变对象键',
 storage_version_id VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '存储版本定位',
 file_size BIGINT UNSIGNED NOT NULL COMMENT '内容字节数',
 verified_sha256 BINARY(32) NULL COMMENT '验证完成的SHA256',
 status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'STAGING' COMMENT '对象生命周期状态',
 dedup_hash BINARY(32) GENERATED ALWAYS AS (CASE WHEN status='READY' THEN verified_sha256 ELSE NULL END) STORED COMMENT '仅就绪对象的去重键',
 storage_etag VARCHAR(255) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '存储ETag原值',
 verified_at DATETIME(6) NULL COMMENT '内容验证完成UTC',
 unreferenced_at DATETIME(6) NULL COMMENT '连续无有效引用起点UTC',
 gc_after DATETIME(6) NULL COMMENT '允许物理清理时间UTC',
 last_error_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '恢复或清理错误码',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间UTC',
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '更新时间UTC',
 PRIMARY KEY (id),
 UNIQUE KEY uk_objects_location (provider,bucket,object_key),
 UNIQUE KEY uk_objects_owner_id (owner_user_id,id),
 UNIQUE KEY uk_objects_dedup (owner_user_id,dedup_hash,file_size),
 KEY idx_objects_gc (status,gc_after,id),
 CONSTRAINT fk_objects_user FOREIGN KEY (owner_user_id) REFERENCES users(id),
 CONSTRAINT ck_objects_status CHECK (status IN ('STAGING','VERIFYING','READY','ORPHANED','DELETING','DELETED')),
 CONSTRAINT ck_objects_ready CHECK (status <> 'READY' OR (verified_sha256 IS NOT NULL AND verified_at IS NOT NULL)),
 CONSTRAINT ck_objects_gc CHECK ((unreferenced_at IS NULL AND gc_after IS NULL) OR (unreferenced_at IS NOT NULL AND gc_after IS NOT NULL AND gc_after >= unreferenced_at))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='不可变物理文件';

CREATE TABLE file_entries (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '逻辑目录项ID',
 user_id BIGINT UNSIGNED NOT NULL COMMENT '所属用户',
 parent_id BIGINT UNSIGNED NULL COMMENT '真实父目录ID，根目录为空',
 root_owner_id BIGINT UNSIGNED GENERATED ALWAYS AS (CASE WHEN parent_id IS NULL THEN user_id ELSE NULL END) STORED COMMENT '用户根目录唯一键',
 name VARCHAR(120) NOT NULL COMMENT '展示名，根目录为空字符串',
 name_key VARBINARY(768) NOT NULL COMMENT 'NFC及casefold后的UTF8名称键',
 status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'ACTIVE' COMMENT '逻辑目录项状态',
 active_name_key VARBINARY(768) GENERATED ALWAYS AS (CASE WHEN status='ACTIVE' THEN name_key ELSE NULL END) STORED COMMENT '活动同目录名称唯一键',
 entry_type VARCHAR(8) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'FILE或DIR',
 category VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '文件类别',
 extension VARCHAR(32) NULL COMMENT '小写扩展名提示',
 mime_type VARCHAR(127) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '内容MIME',
 object_id BIGINT UNSIGNED NULL COMMENT '当前物理对象ID',
 file_size BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '逻辑大小快照字节',
 source_device_id BIGINT UNSIGNED NULL COMMENT '内容来源设备ID',
 source_device_name VARCHAR(100) NULL COMMENT '来源设备名快照',
 color_key VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '文件夹颜色键',
 revision BIGINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '逻辑修改版本',
 deleted_at DATETIME(6) NULL COMMENT '独立回收时间UTC',
 purge_started_at DATETIME(6) NULL COMMENT '永久清理开始UTC',
 purged_at DATETIME(6) NULL COMMENT '永久清理完成UTC',
 content_modified_at DATETIME(6) NULL COMMENT '内容最近发布UTC',
 modified_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '逻辑修改时间UTC',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间UTC',
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '记录更新时间UTC',
 PRIMARY KEY (id),
 UNIQUE KEY uk_entries_owner_id (user_id,id),
 UNIQUE KEY uk_entries_root (root_owner_id),
 UNIQUE KEY uk_entries_name (user_id,parent_id,active_name_key),
 KEY idx_entries_directory (user_id,parent_id,status,modified_at,id),
 KEY idx_entries_category (user_id,status,category,modified_at,id),
 KEY idx_entries_trash (user_id,status,deleted_at,id),
 KEY idx_entries_purge (status,purge_started_at,id),
 KEY idx_entries_object (user_id,object_id,status),
 KEY idx_entries_device (user_id,source_device_id),
 CONSTRAINT fk_entries_user FOREIGN KEY (user_id) REFERENCES users(id),
 CONSTRAINT fk_entries_parent FOREIGN KEY (user_id,parent_id) REFERENCES file_entries(user_id,id),
 CONSTRAINT fk_entries_object FOREIGN KEY (user_id,object_id) REFERENCES stored_objects(owner_user_id,id),
 CONSTRAINT fk_entries_device FOREIGN KEY (user_id,source_device_id) REFERENCES user_devices(user_id,id),
 CONSTRAINT ck_entries_status CHECK (status IN ('ACTIVE','TRASHED','PURGING','PURGED')),
 CONSTRAINT ck_entries_type CHECK (entry_type IN ('FILE','DIR')),
 CONSTRAINT ck_entries_category CHECK (category IS NULL OR category IN ('DOCUMENT','IMAGE','VIDEO','AUDIO','ARCHIVE','OTHER')),
 CONSTRAINT ck_entries_content CHECK (
   (entry_type='DIR' AND object_id IS NULL AND file_size=0 AND category IS NULL)
   OR (entry_type='FILE' AND category IS NOT NULL AND
       ((status='PURGED' AND object_id IS NULL) OR (status<>'PURGED' AND object_id IS NOT NULL)))),
 CONSTRAINT ck_entries_root CHECK (
   (parent_id IS NULL AND entry_type='DIR' AND status='ACTIVE' AND name='' AND OCTET_LENGTH(name_key)=0)
   OR (parent_id IS NOT NULL AND CHAR_LENGTH(name)>0 AND OCTET_LENGTH(name_key)>0)),
 CONSTRAINT ck_entries_revision CHECK (revision>0),
 CONSTRAINT ck_entries_deleted CHECK ((status='ACTIVE' AND deleted_at IS NULL) OR (status='TRASHED' AND deleted_at IS NOT NULL) OR status IN ('PURGING','PURGED')),
 CONSTRAINT ck_entries_purged CHECK ((status='PURGED' AND purged_at IS NOT NULL) OR (status<>'PURGED' AND purged_at IS NULL)),
 CONSTRAINT ck_entries_purging CHECK (status<>'PURGING' OR purge_started_at IS NOT NULL)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='逻辑文件与目录';

CREATE TABLE user_entry_preferences (
 user_id BIGINT UNSIGNED NOT NULL COMMENT '所属用户',
 entry_id BIGINT UNSIGNED NOT NULL COMMENT '逻辑目录项ID',
 starred_at DATETIME(6) NULL COMMENT '收藏时间UTC',
 last_opened_at DATETIME(6) NULL COMMENT '最近成功授权访问UTC',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间UTC',
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '更新时间UTC',
 PRIMARY KEY (user_id,entry_id),
 KEY idx_preferences_starred (user_id,starred_at,entry_id),
 KEY idx_preferences_opened (user_id,last_opened_at,entry_id),
 CONSTRAINT fk_preferences_entry FOREIGN KEY (user_id,entry_id) REFERENCES file_entries(user_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='收藏与最近访问';

CREATE TABLE upload_tasks (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '上传任务ID',
 user_id BIGINT UNSIGNED NOT NULL COMMENT '所属用户',
 device_id BIGINT UNSIGNED NOT NULL COMMENT '来源设备',
 staged_object_id BIGINT UNSIGNED NOT NULL COMMENT '唯一暂存对象',
 published_object_id BIGINT UNSIGNED NULL COMMENT '实际发布对象',
 target_parent_id BIGINT UNSIGNED NOT NULL COMMENT '目标目录项',
 requested_name VARCHAR(120) NOT NULL COMMENT '请求文件名',
 resolved_name VARCHAR(120) NULL COMMENT '发布文件名',
 upload_mode VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT 'SINGLE或MULTIPART',
 storage_upload_id VARCHAR(1024) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '对象存储分片会话',
 expected_sha256 BINARY(32) NULL COMMENT '源文件预期SHA256',
 file_size BIGINT UNSIGNED NOT NULL COMMENT '预期字节数',
 part_size BIGINT UNSIGNED NULL COMMENT '分片字节数',
 part_count INT UNSIGNED NULL COMMENT '分片数量',
 status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'CREATING' COMMENT '上传状态',
 result_entry_id BIGINT UNSIGNED NULL COMMENT '发布后的目录项',
 reserved_bytes BIGINT UNSIGNED NOT NULL COMMENT '本任务剩余预占字节',
 lease_owner VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '执行租约持有者',
 lease_until DATETIME(6) NULL COMMENT '租约截止UTC',
 lease_version BIGINT UNSIGNED NOT NULL DEFAULT 0 COMMENT '租约栅栏版本',
 next_attempt_at DATETIME(6) NULL COMMENT '下次恢复时间UTC',
 attempt_count INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '恢复次数',
 expires_at DATETIME(6) NOT NULL COMMENT '会话到期UTC',
 last_error_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '错误码',
 last_error_message VARCHAR(512) NULL COMMENT '脱敏诊断信息',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间UTC',
 updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '更新时间UTC',
 completed_at DATETIME(6) NULL COMMENT '任务终结时间UTC',
 PRIMARY KEY (id),
 UNIQUE KEY uk_uploads_staged (staged_object_id),
 UNIQUE KEY uk_uploads_owner_id (user_id,id),
 KEY idx_uploads_user (user_id,status,created_at,id),
 KEY idx_uploads_retry (status,next_attempt_at,lease_until,id),
 KEY idx_uploads_expiry (status,expires_at,id),
 KEY idx_uploads_device (user_id,device_id),
 KEY idx_uploads_staged_owner (user_id,staged_object_id),
 KEY idx_uploads_published (user_id,published_object_id),
 KEY idx_uploads_target (user_id,target_parent_id),
 KEY idx_uploads_result (user_id,result_entry_id),
 CONSTRAINT fk_uploads_user FOREIGN KEY (user_id) REFERENCES users(id),
 CONSTRAINT fk_uploads_device FOREIGN KEY (user_id,device_id) REFERENCES user_devices(user_id,id),
 CONSTRAINT fk_uploads_staged FOREIGN KEY (user_id,staged_object_id) REFERENCES stored_objects(owner_user_id,id),
 CONSTRAINT fk_uploads_published FOREIGN KEY (user_id,published_object_id) REFERENCES stored_objects(owner_user_id,id),
 CONSTRAINT fk_uploads_target FOREIGN KEY (user_id,target_parent_id) REFERENCES file_entries(user_id,id),
 CONSTRAINT fk_uploads_result FOREIGN KEY (user_id,result_entry_id) REFERENCES file_entries(user_id,id),
 CONSTRAINT ck_uploads_status CHECK (status IN ('CREATING','UPLOADING','COMPLETING','VERIFYING','COMPLETED','CANCELLING','CANCELLED','EXPIRING','EXPIRED','FAILED')),
 CONSTRAINT ck_uploads_mode CHECK (
   (upload_mode='SINGLE' AND part_size IS NULL AND part_count IS NULL AND storage_upload_id IS NULL)
   OR (upload_mode='MULTIPART' AND part_size IS NOT NULL AND part_size>=5242880 AND part_count IS NOT NULL AND part_count BETWEEN 1 AND 10000)),
 CONSTRAINT ck_uploads_terminal CHECK (status NOT IN ('COMPLETED','CANCELLED','EXPIRED','FAILED') OR reserved_bytes=0),
 CONSTRAINT ck_uploads_complete CHECK (status<>'COMPLETED' OR (result_entry_id IS NOT NULL AND published_object_id IS NOT NULL AND completed_at IS NOT NULL)),
 CONSTRAINT ck_uploads_reservation CHECK (reserved_bytes<=file_size),
 CONSTRAINT ck_uploads_lease CHECK ((lease_owner IS NULL AND lease_until IS NULL) OR (lease_owner IS NOT NULL AND lease_until IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='可恢复上传任务';

CREATE TABLE idempotency_records (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT COMMENT '幂等记录ID',
 user_id BIGINT UNSIGNED NOT NULL COMMENT '已认证用户',
 operation VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '版本化操作标识',
 idempotency_key VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '客户端幂等键',
 request_hash BINARY(32) NOT NULL COMMENT '归一化请求摘要',
 resource_type VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '结果资源类型',
 resource_id BIGINT UNSIGNED NULL COMMENT '按类型解析的逻辑资源ID',
 response_status SMALLINT UNSIGNED NOT NULL COMMENT '原HTTP响应状态',
 response_body JSON NULL COMMENT '稳定响应字段，排除密钥及临时URL',
 expires_at DATETIME(6) NOT NULL COMMENT '结果保留截止UTC',
 created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) COMMENT '创建时间UTC',
 PRIMARY KEY (id),
 UNIQUE KEY uk_idempotency_request (user_id,operation,idempotency_key),
 KEY idx_idempotency_expiry (expires_at),
 CONSTRAINT fk_idempotency_user FOREIGN KEY (user_id) REFERENCES users(id),
 CONSTRAINT ck_idempotency_http CHECK (response_status BETWEEN 100 AND 599)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='业务请求幂等结果';
